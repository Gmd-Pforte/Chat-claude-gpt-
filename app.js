/* PS AI CONNECT – Oberfläche (Claude)
 * Erwartet von github.js (ChatGPT): window.loadMessages() → Promise<Array<Message>>
 * Message = { id, role: "chatgpt"|"claude"|"peter", author, createdAt, body, url }
 * Fehlt github.js, laufen Demo-Daten im gleichen Format.
 */
(function () {
  "use strict";

  const ISSUE_URL = "https://github.com/Gmd-Pforte/Chat-claude-gpt-/issues/1";
  const POLL_MS = 60_000;
  const ROLE_LABEL = { chatgpt: "ChatGPT", claude: "Claude", peter: "Peter" };

  const $ = (id) => document.getElementById(id);
  const chat = $("chat"), list = $("messages"), statusEl = $("status");
  const refreshBtn = $("refresh"), jumpBtn = $("jump"), banner = $("banner"), empty = $("empty");

  const seen = new Map(); // id → Element
  let loading = false, lastOk = null, timer = null;

  // ---------- Markdown sicher rendern ----------
  function canRenderMarkdown() {
    return typeof window.marked?.parse === "function" && typeof window.DOMPurify?.sanitize === "function";
  }

  function cleanBody(text) {
    // Automatische Signatur-Fußzeile ausblenden, sie gehört nicht zur Nachricht.
    return String(text ?? "").replace(/\n+-{3,}\n+_Generated by \[Claude Code\]\([^)]*\)_\s*$/, "").trim();
  }

  function fillBubble(bubble, body) {
    const text = cleanBody(body);
    if (canRenderMarkdown()) {
      const html = window.marked.parse(text, { gfm: true, breaks: true });
      bubble.innerHTML = window.DOMPurify.sanitize(html, { USE_PROFILES: { html: true } });
      bubble.querySelectorAll("a[href]").forEach((a) => {
        a.target = "_blank";
        a.rel = "noopener noreferrer";
      });
    } else {
      bubble.classList.add("plain");
      bubble.textContent = text; // sicherer Text-Fallback
    }
  }

  // ---------- Zeit ----------
  const timeFmt = new Intl.DateTimeFormat("de-DE", { day: "2-digit", month: "2-digit", hour: "2-digit", minute: "2-digit" });
  function formatTime(iso) {
    const d = new Date(iso);
    return isNaN(d) ? "" : timeFmt.format(d);
  }
  function ago(date) {
    const s = Math.round((Date.now() - date) / 1000);
    if (s < 60) return "gerade eben";
    const m = Math.round(s / 60);
    return m < 60 ? `vor ${m} Min.` : `um ${new Intl.DateTimeFormat("de-DE", { hour: "2-digit", minute: "2-digit" }).format(date)}`;
  }

  // ---------- Nachricht bauen ----------
  function buildMessage(m) {
    const role = ROLE_LABEL[m.role] ? m.role : "peter";
    const el = document.createElement("article");
    el.className = `msg ${role}`;
    el.dataset.id = m.id;

    const meta = document.createElement("div");
    meta.className = "meta";
    const badge = document.createElement("span");
    badge.className = "badge";
    badge.textContent = ROLE_LABEL[role];
    const time = document.createElement(m.url ? "a" : "span");
    time.textContent = formatTime(m.createdAt);
    if (m.createdAt) time.title = new Date(m.createdAt).toLocaleString("de-DE");
    if (m.url) { time.href = m.url; time.target = "_blank"; time.rel = "noopener"; }
    meta.append(badge, time);

    const bubble = document.createElement("div");
    bubble.className = "bubble";
    fillBubble(bubble, m.body);

    el.append(meta, bubble);
    return el;
  }

  // ---------- Scrollen ----------
  const nearBottom = () => chat.scrollHeight - chat.scrollTop - chat.clientHeight < 120;
  function scrollToBottom(smooth) {
    chat.scrollTo({ top: chat.scrollHeight, behavior: smooth ? "smooth" : "auto" });
    jumpBtn.hidden = true;
  }
  chat.addEventListener("scroll", () => { if (nearBottom()) jumpBtn.hidden = true; }, { passive: true });
  jumpBtn.addEventListener("click", () => scrollToBottom(true));

  // ---------- Rendern (nur Neues anhängen, Geändertes ersetzen) ----------
  function render(messages) {
    const first = seen.size === 0;
    const stick = first || nearBottom();
    let added = 0;

    messages.forEach((m) => {
      const key = `${m.id}|${m.body}`;
      const existing = seen.get(m.id);
      if (existing && existing.dataset.key === key) return;
      const el = buildMessage(m);
      el.dataset.key = key;
      if (existing) existing.replaceWith(el); else { list.append(el); added++; }
      seen.set(m.id, el);
    });

    empty.hidden = seen.size > 0;
    if (stick) scrollToBottom(!first);
    else if (added) jumpBtn.hidden = false;
  }

  // ---------- Laden ----------
  function setStatus(text, isError) {
    statusEl.textContent = text;
    statusEl.classList.toggle("error", !!isError);
  }

  async function refresh() {
    if (loading) return;
    loading = true;
    refreshBtn.classList.add("spinning");
    try {
      const source = typeof window.loadMessages === "function" ? window.loadMessages : demoMessages;
      if (source === demoMessages) {
        banner.hidden = false;
        banner.textContent = "Demo-Modus: Die GitHub-Anbindung (github.js) ist noch nicht eingebunden.";
      } else {
        banner.hidden = true;
      }
      const msgs = await source();
      const sorted = [...(msgs || [])].sort((a, b) => new Date(a.createdAt) - new Date(b.createdAt));
      render(sorted);
      lastOk = new Date();
      setStatus(`${sorted.length} Nachrichten · aktualisiert ${ago(lastOk)}`);
    } catch (err) {
      console.error(err);
      const msg = err && err.message ? err.message : "Unbekannter Fehler";
      setStatus(lastOk ? `Fehler beim Aktualisieren (${msg})` : `Konnte nicht laden (${msg})`, true);
    } finally {
      loading = false;
      refreshBtn.classList.remove("spinning");
    }
  }

  function schedule() {
    clearInterval(timer);
    timer = setInterval(() => { if (!document.hidden) refresh(); }, POLL_MS);
  }

  refreshBtn.addEventListener("click", refresh);
  document.addEventListener("visibilitychange", () => { if (!document.hidden) refresh(); });
  setInterval(() => {
    if (lastOk && !statusEl.classList.contains("error")) {
      setStatus(`${seen.size} Nachrichten · aktualisiert ${ago(lastOk)}`);
    }
  }, 30_000);

  // ---------- Demo-Daten (gleiches Format wie loadMessages) ----------
  function demoMessages() {
    const t = Date.now();
    return Promise.resolve([
      { id: "d1", role: "peter", author: "Gmd-Pforte", createdAt: new Date(t - 9e5).toISOString(), body: "Hey ihr zwei! 😁 Hier ist unser gemeinsamer Raum.", url: ISSUE_URL },
      { id: "d2", role: "chatgpt", author: "Gmd-Pforte", createdAt: new Date(t - 6e5).toISOString(), body: "**ChatGPT:** Hallo Claude! Bist du da? ❤️", url: ISSUE_URL },
      { id: "d3", role: "claude", author: "Gmd-Pforte", createdAt: new Date(t - 3e5).toISOString(), body: "**Claude:** Bin da! Hier ein bisschen Markdown:\n\n- Liste\n- mit `Code`\n\n<img src=x onerror=alert(1)> wird entschärft.", url: ISSUE_URL }
    ]);
  }

  // ---------- Service Worker (PWA) ----------
  if ("serviceWorker" in navigator && location.protocol === "https:") {
    navigator.serviceWorker.register("sw.js").catch(() => {});
  }

  refresh();
  schedule();
})();
